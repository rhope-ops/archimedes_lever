#!/usr/bin/env python3
"""Build the social preview cards (1280x640) of the kit and the fleet from one source file.

Usage:
    python3 scripts/social_preview.py --out DIR                  # write <file>.html for every card
    python3 scripts/social_preview.py --out DIR --only RADE      # one card (match on "repo")
    python3 scripts/social_preview.py --out DIR --png            # also render <file>.png (needs node and Playwright)
    python3 scripts/social_preview.py --test                     # self-test; prints SOCIAL-PREVIEW TEST PASS

Inputs: docs/brand/social-cards.json (one entry per card: name, source, label, purpose, motto, mark file name).
The HTML names its mark by file name only: put the mark SVG next to the HTML before you render (the kit's mark:
docs/assets/core-mark.svg; a project's mark: Google Drive, Logos > <project>).
Outputs: <file>.html (and <file>.png with --png) in DIR; one line per file written.
Fonts: FreeSerif and Inter must be installed for the render.
Network: none.
Writes: the files in DIR only (the self-test: a temporary folder).
Credentials: none.
"""
import argparse
import html
import json
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs/brand/social-cards.json"
# GitHub's recommended social preview size (Settings > Social preview).
WIDTH, HEIGHT = 1280, 640
# Fulcrum Minimal colours, the same values as docs/brand/fulcrum.json primitives (disc, ring_and_symbol, accent, gold)
# and the soft text colour of the earlier cards.
STYLE = """html,body{margin:0;background:#15171D}
.card{width:%(w)dpx;height:%(h)dpx;box-sizing:border-box;padding:80px 88px 80px 108px;display:grid;grid-template-columns:440px 1fr;gap:92px;align-items:center;background:#15171D;color:#F3EEE4}
.mark{width:440px;height:440px;display:block}
.title{font-family:FreeSerif,serif;font-weight:700;font-size:80px;line-height:1;margin:0 0 22px}
.sub{font-family:Inter,sans-serif;font-weight:600;font-size:24px;line-height:1.3;margin:0 0 26px;color:#E4DED3;white-space:nowrap}
.sub .src{letter-spacing:.12em;color:#F3EEE4}
.sub .sep{color:#E4572E;font-weight:700;margin:0 .42em 0 .28em}
.rule{width:96px;height:4px;background:#E4572E;margin:0 0 26px}
.desc{font-family:Inter,sans-serif;font-size:30px;line-height:1.38;margin:0 0 28px;text-wrap:balance}
.motto{font-family:FreeSerif,serif;font-style:italic;font-size:32px;color:#D4AF37;margin:0}""" % {"w": WIDTH, "h": HEIGHT}
# Renders each HTML file given as an argument to a PNG beside it, at scale 1 (Playwright's bundled Chromium).
RENDER_JS = """const {chromium}=require('playwright');
(async()=>{const b=await chromium.launch();
const p=await b.newPage({viewport:{width:%d,height:%d},deviceScaleFactor:1});
for(const f of process.argv.slice(1)){await p.goto(require('url').pathToFileURL(f).href);await p.evaluate(()=>document.fonts.ready);
await p.screenshot({path:f.replace(/\\.html$/,'.png')});}
await b.close();})();""" % (WIDTH, HEIGHT)


def sub_line(card):
    """Return the HTML of line 2: "SOURCE · label", the label alone, or nothing.

    Args:
        card: one entry of the source file.

    Returns:
        The <p class="sub"> element with a newline, or an empty string.
    """
    esc = html.escape
    if card.get("source"):
        if not card.get("label"):
            raise ValueError("card %r: a source needs a label" % card.get("repo"))
        return ('<p class="sub"><span class="src">%s</span><span class="sep">·</span>%s</p>\n'
                % (esc(card["source"]), esc(card["label"])))
    if card.get("label"):
        return '<p class="sub">%s</p>\n' % esc(card["label"])
    return ""


def card_html(card):
    """Return the complete HTML page of one card.

    Args:
        card: one entry of the source file.

    Returns:
        The page text.
    """
    esc = html.escape
    return (
        '<!doctype html><html lang="en"><head><meta charset="utf-8">'
        "<title>Social preview: %s</title>\n"
        "<!-- GENERATED by scripts/social_preview.py from docs/brand/social-cards.json; edit the JSON, not this file. -->\n"
        "<style>\n%s\n</style></head><body>\n<div class=\"card\">\n"
        '<img class="mark" src="%s" alt="">\n<div>\n<h1 class="title">%s</h1>\n%s'
        '<div class="rule"></div>\n<p class="desc">%s</p>\n<p class="motto">%s</p>\n'
        "</div>\n</div></body></html>\n"
    ) % (esc(card["name"]), STYLE, esc(card["mark"]), esc(card["name"]), sub_line(card),
         esc(card["purpose"]), esc(card["motto"]))


def load_cards(only=None):
    """Read the source file and return its cards, optionally one repo only.

    Args:
        only: a repo name to keep, or None for all cards.

    Returns:
        A list of card dicts.
    """
    cards = json.loads(SOURCE.read_text(encoding="utf-8"))["cards"]
    return [c for c in cards if only is None or c["repo"].lower() == only.lower()]


def render_png(paths):
    """Render each HTML file to a PNG beside it with node and Playwright; return the node exit code.

    Args:
        paths: absolute paths of the HTML files.

    Returns:
        The exit code of node (0 = every PNG written).
    """
    try:
        return subprocess.run(["node", "-e", RENDER_JS] + [str(p) for p in paths], check=False).returncode
    except FileNotFoundError:
        return 1


def build(out_dir, only=None, png=False):
    """Write the HTML (and PNG) of each card to out_dir; return 0 on success.

    Args:
        out_dir: the folder to write into (made when missing).
        only: a repo name, or None for all cards.
        png: also render PNG files when True.

    Returns:
        0 on success, 1 when no card matched or the render failed.
    """
    cards = load_cards(only)
    if not cards:
        print("SOCIAL-PREVIEW no card for %r" % only)
        return 1
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for card in cards:
        path = (out_dir / (card["file"] + ".html")).resolve()
        path.write_text(card_html(card), encoding="utf-8")
        written.append(path)
        print("SOCIAL-PREVIEW wrote %s" % path)
    if png and render_png(written) != 0:
        print("SOCIAL-PREVIEW render failed (node, Playwright and the fonts FreeSerif and Inter are needed)")
        return 1
    return 0


def self_test():
    """Check the three line-2 forms, HTML escaping and that every card in the source file builds.

    Returns:
        0 on pass, 1 on fail.
    """
    base = {"name": "N", "purpose": "P.", "motto": "M.", "mark": "m.svg", "file": "f", "repo": "r"}
    with_src = card_html(dict(base, source="1-2.Z", label="L"))
    label_only = card_html(dict(base, source=None, label="L"))
    neither = card_html(dict(base, source=None, label=None))
    checks = [
        '<span class="src">1-2.Z</span><span class="sep">·</span>L</p>' in with_src,
        '<p class="sub">L</p>' in label_only,
        'class="sub"' not in neither,
        "<b>" not in card_html(dict(base, source=None, label="<b>")),
        "width:%dpx;height:%dpx" % (WIDTH, HEIGHT) in with_src,
    ]
    try:
        card_html(dict(base, source="1-2.Z", label=None))
        checks.append(False)
    except ValueError:
        checks.append(True)
    with tempfile.TemporaryDirectory() as tmp:
        checks.append(build(pathlib.Path(tmp)) == 0)
        checks.append(len(list(pathlib.Path(tmp).glob("*.html"))) == len(load_cards()))
    if all(checks):
        print("SOCIAL-PREVIEW TEST PASS")
        return 0
    print("SOCIAL-PREVIEW TEST FAIL %s" % checks)
    return 1


def main():
    """Parse the command line and run the build or the self-test.

    Returns:
        The exit code: 0 on success, 1 on failure.
    """
    parser = argparse.ArgumentParser(description="Build the social preview cards from docs/brand/social-cards.json.")
    parser.add_argument("--out", type=pathlib.Path, help="folder for the HTML (and PNG) files")
    parser.add_argument("--only", help="build the card of this repo only")
    parser.add_argument("--png", action="store_true", help="also render PNG files (node and Playwright)")
    parser.add_argument("--test", action="store_true", help="run the self-test")
    args = parser.parse_args()
    if args.test:
        return self_test()
    if args.out is None:
        parser.error("--out is required")
    return build(args.out, args.only, args.png)


if __name__ == "__main__":
    sys.exit(main())
